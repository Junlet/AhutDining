def _kcal(protein: float, fat: float, carbs: float) -> float:
    return round(protein * 4 + fat * 9 + carbs * 4, 1)


def _flags(raw: str) -> dict:
    return {
        "is_staple": 1 if "S" in raw else 0,
        "is_vegetable": 1 if "V" in raw else 0,
        "is_self_service": 1 if "Z" in raw else 0,
    }


def seed(force: bool = False) -> dict:
    """写入示例数据；force=True 时清空重建（会连带清掉收藏/评论）。"""
    conn = connect()
    conn.row_factory = sqlite3.Row
    existing = conn.execute("SELECT COUNT(*) AS c FROM dishes").fetchone()["c"]
    if existing and not force:
        return {"skipped": True, "dishes": existing}

    if force:
        conn.executescript(
            "DELETE FROM comments; DELETE FROM favorites; DELETE FROM images;"
            "DELETE FROM dishes; DELETE FROM windows; DELETE FROM canteens;"
        )

    canteen_ids: dict[tuple[str, str], int] = {}
    for campus, name, note in CANTEENS:
        cur = conn.execute(
            "INSERT OR IGNORE INTO canteens (campus, name, note) VALUES (?, ?, ?)",
            (campus, name, note),
        )
        if cur.lastrowid:
            canteen_ids[(campus, name)] = cur.lastrowid
        else:
            row = conn.execute(
                "SELECT id FROM canteens WHERE campus = ? AND name = ?", (campus, name)
            ).fetchone()
            canteen_ids[(campus, name)] = row["id"]

    window_ids: dict[tuple[str, str], int] = {}
    for campus, canteen, window, floor, hours in WINDOWS:
        cid = canteen_ids[(campus, canteen)]
        cur = conn.execute(
            "INSERT OR IGNORE INTO windows (canteen_id, name, floor, open_hours) VALUES (?, ?, ?, ?)",
            (cid, window, floor, hours),
        )
        if cur.lastrowid:
            window_ids[(canteen, window)] = cur.lastrowid
        else:
            row = conn.execute(
                "SELECT id FROM windows WHERE canteen_id = ? AND name = ?", (cid, window)
            ).fetchone()
            window_ids[(canteen, window)] = row["id"]

    inserted = 0
    for canteen, window, name, category, price, protein, fat, carbs, flags, tags, note in DISHES:
        wid = window_ids.get((canteen, window))
        if not wid:
            raise ValueError(f"窗口未登记: {canteen} / {window}")
        f = _flags(flags)
        conn.execute(
            """INSERT INTO dishes
               (name, window_id, category, price, unit, kcal, protein, fat, carbs,
                is_staple, is_vegetable, is_self_service, tags, note, active)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,1)""",
            (name, wid, category, price, "份", _kcal(protein, fat, carbs),
             protein, fat, carbs, f["is_staple"], f["is_vegetable"],
             f["is_self_service"], tags, note),
        )
        inserted += 1
    conn.commit()
    return {
        "skipped": False,
        "canteens": len(canteen_ids),
        "windows": len(window_ids),
        "dishes": inserted,
        "seeded_at": now(),
    }


